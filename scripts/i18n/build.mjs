// NIGHTFALL 汉化: scripts/i18n/zh/*.json → src/shared/i18n/zh.generated.js
//
//   node scripts/i18n/build.mjs
//
// Each zh/<chunk>.json maps the English of scripts/i18n/chunks/<chunk>.json
// to Chinese; zh/extra.json adds words built into sentences at run time and
// fixes made after review (it wins). Strings that map to themselves (code,
// fonts, debug text) are left out: the runtime shows anything it does not
// find unchanged. Keys starting with "_" are notes.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const DIR = path.join(ROOT, 'scripts/i18n/zh');
const OUT = path.join(ROOT, 'src/shared/i18n/zh.generated.js');

export function buildTable() {
  const names = fs.readdirSync(DIR).filter((n) => n.endsWith('.json')).sort((a, b) => (a === 'extra.json') - (b === 'extra.json') || a.localeCompare(b));
  const table = {};
  for (const name of names) {
    const chunk = JSON.parse(fs.readFileSync(path.join(DIR, name), 'utf8'));
    for (const [key, zh] of Object.entries(chunk)) {
      if (key.startsWith('_') || typeof zh !== 'string' || zh === key || !zh.trim()) continue;
      table[key] = zh;
    }
  }
  return Object.fromEntries(Object.entries(table).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const table = buildTable();
  const body = `// Generated by scripts/i18n/build.mjs from scripts/i18n/zh/*.json. Do not edit.\n// ${Object.keys(table).length} strings.\nexport default JSON.parse(${JSON.stringify(JSON.stringify(table))});\n`;
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, body);
  console.log(`${Object.keys(table).length} strings → ${path.relative(ROOT, OUT)} (${(body.length / 1024).toFixed(0)} KB)`);
}
