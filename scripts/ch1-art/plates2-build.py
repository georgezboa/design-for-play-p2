def tag_body(rgb, alpha):
    """The manila body of a cut tag (not its string): corners TL, TR, BR, BL."""
    lum = luma(rgb)
    sat = rgb.max(2) - rgb.min(2)
    m = ((lum > 0.55) & (sat > 0.12) & (alpha > 0.5)).astype(np.uint8)
    m = cv2.morphologyEx(m, cv2.MORPH_OPEN, np.ones((5, 5), np.uint8))
    n, lab, st, _ = cv2.connectedComponentsWithStats(m)
    i = 1 + int(np.argmax(st[1:, 4]))
    cnt, _ = cv2.findContours((lab == i).astype(np.uint8), cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    pts = cv2.boxPoints(cv2.minAreaRect(max(cnt, key=cv2.contourArea)))
    pts = sorted(pts.tolist(), key=lambda p: p[1])
    top = sorted(pts[:2], key=lambda p: p[0])
    bottom = sorted(pts[2:], key=lambda p: p[0])
    return [top[0], top[1], bottom[1], bottom[0]]


def quad_in(c, s0, s1, t0, t1):
    """A sub-quad of quad c (TL, TR, BR, BL) from s0..s1 across and t0..t1 down."""
    c = np.float32(c)

    def at(s, t):
        top = c[0] + (c[1] - c[0]) * s
        bot = c[3] + (c[2] - c[3]) * s
        return tuple(top + (bot - top) * t)
    return [at(s0, t0), at(s1, t0), at(s1, t1), at(s0, t1)]


