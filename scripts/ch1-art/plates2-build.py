def write_manifests():
    for act, title in (('act2', 'Act 2 · THE LUGGAGE CAR'), ('act3', 'Act 3 · TWO TRUE THINGS')):
        rows = [(k, v) for k, v in OUTPUTS.items() if k.startswith(act + '/')]
        if not rows:
            continue
        total = sum(v['bytes'] for _, v in rows)
        lines = [
            f'# {title}: painted plates',
            '',
            f'Sources: George\'s Chapter 1 paintings, {CREDIT}. The panoramas behind the',
            'interim plates come from `src/assets/generated/worlds/` (see that folder\'s own credits).',
            '',
            'Every file here is generated by `python3 -I scripts/ch1-art/plates2-build.py` from the',
            'read-only 1536×1024 sources; do not edit them by hand. Crop boxes are source pixels',
            '(x, y, w, h); scenes are WebP q86, sprites and frames WebP with alpha.',
            '',
            '| Output | Size | KB | Source | Crop box | What it is |',
            '|---|---|---|---|---|---|',
        ]
        for k, v in rows:
            cropbox = ', '.join(str(int(round(x))) for x in v['crop']) if v['crop'] else '—'
            lines.append(f"| `{k.split('/', 1)[1]}.webp` | {v['w']}×{v['h']} | {v['bytes'] / 1024:.0f} | {', '.join(v['sources'])} | {cropbox} | {v['note']} |")
        lines += ['', f'Total: {total / 1024 / 1024:.2f} MB.', '']
        if REGISTRATION:
            lines += ['## 1978 registration', '', 'Each 1978 painting is feature-matched onto its present (SIFT, RANSAC similarity) and cropped identically, so the lens shows one through the other in register.', '',
                      '| Pair | Inliers | Residual px | Offset px | Warped |', '|---|---|---|---|---|']
            for k, r in REGISTRATION.items():
                if (act == 'act2') == k.startswith('A2'):
                    lines.append(f"| {k} / {k}-1978 | {r['inliers']} | {r['residualPx']} | {r['maxCornerOffsetPx']} | {'yes' if r['warped'] else 'no'} |")
            lines.append('')
        (OUT / act / 'ASSET_MANIFEST.md').write_text('\n'.join(lines))
        print(f'  wrote public/assets/ch1-painted/{act}/ASSET_MANIFEST.md ({total / 1024 / 1024:.2f} MB)')


def write_js(name, title, consts):
    lines = [
        f'// GENERATED by scripts/ch1-art/plates2-build.py — do not edit by hand.',
        f'// {title}: plate URLs and the painted objects\' boxes, measured on the',
        '// processed plates (tile-normalised [x, y, w, h] / [u, v]).',
        '',
    ]
    def plain(o):
        if isinstance(o, dict):
            return {k: plain(v) for k, v in o.items()}
        if isinstance(o, (list, tuple)):
            return [plain(v) for v in o]
        if isinstance(o, (np.floating, float)):
            return round(float(o), 4)
        if isinstance(o, np.integer):
            return int(o)
        return o
    for key, value in consts.items():
        lines.append(f'export const {key} = Object.freeze({json.dumps(plain(value))});')
    (JS / name).write_text('\n'.join(lines) + '\n')
    print(f'  wrote src/chapters/nightService/art/{name}')


