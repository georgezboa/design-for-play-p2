# registration of a 1978 plate onto its present (the lens shows one through the other)

REGISTRATION = {}


def register(name, present, past):
    """Feature-match past onto present (SIFT + RANSAC similarity); warp when it is off by more than half a pixel."""
    ga = cv2.cvtColor(to_u8(present), cv2.COLOR_RGB2GRAY)
    gb = cv2.cvtColor(to_u8(past), cv2.COLOR_RGB2GRAY)
    clahe = cv2.createCLAHE(3.0, (8, 8))
    ga, gb = clahe.apply(ga), clahe.apply(gb)
    sift = cv2.SIFT_create(6000)
    ka, da = sift.detectAndCompute(ga, None)
    kb, db = sift.detectAndCompute(gb, None)
    good = [m for m, n in cv2.BFMatcher().knnMatch(db, da, k=2) if m.distance < 0.7 * n.distance]
    pb = np.float32([kb[m.queryIdx].pt for m in good])
    pa = np.float32([ka[m.trainIdx].pt for m in good])
    M, mask = cv2.estimateAffinePartial2D(pb, pa, ransacReprojThreshold=2.0)
    inl = mask.ravel() == 1
    res = np.linalg.norm(pb[inl] @ M[:, :2].T + M[:, 2] - pa[inl], axis=1)
    scale = math.hypot(M[0, 0], M[1, 0])
    shift = (float(M[0, 2]), float(M[1, 2]))
    warped = False
    corner = np.array([[0, 0], [past.shape[1], past.shape[0]]], np.float32) @ M[:, :2].T + M[:, 2] - np.array([[0, 0], [past.shape[1], past.shape[0]]])
    if np.abs(corner).max() > 0.5:
        past = cv2.warpAffine(past, M, (present.shape[1], present.shape[0]), flags=cv2.INTER_LANCZOS4, borderMode=cv2.BORDER_REFLECT)
        warped = True
    REGISTRATION[name] = {
        'matches': int(len(good)), 'inliers': int(inl.sum()), 'residualPx': round(float(np.median(res)), 2),
        'scale': round(scale, 5), 'shiftPx': [round(shift[0], 2), round(shift[1], 2)],
        'maxCornerOffsetPx': round(float(np.abs(corner).max()), 2), 'warped': warped,
    }
    print(f'  register {name}: {len(good)} matches, {inl.sum()} inliers, residual {np.median(res):.2f}px, '
          f'max offset {np.abs(corner).max():.2f}px → {"warped" if warped else "already in register"}')
    return past


