def cut_prop(box, *, seed, thresh=0.07, erode=1, drop_neutral=True):
    """Key one prop off the grey sheet: (rgb, alpha) cropped to box."""
    props = load('C-props')
    x, y, w, h = box
    rgb = props[y:y + h, x:x + w]
    grey = np.array([127, 127, 127], np.float32) / 255
    dist = np.linalg.norm(rgb - grey, axis=2)
    # the sheet's hatching shadows are near-neutral: keep only what differs in tone or hue
    sat = rgb.max(axis=2) - rgb.min(axis=2)
    fg = ((dist > thresh) & ((sat > 0.06) | (np.abs(luma(rgb) - 0.5) > 0.16))).astype(np.uint8)
    if drop_neutral:
        fg &= (sat > 0.045).astype(np.uint8)
    fg = cv2.morphologyEx(fg, cv2.MORPH_CLOSE, np.ones((5, 5), np.uint8))
    n, lab, stats, _ = cv2.connectedComponentsWithStats(fg, 8)
    sx, sy = seed[0] - x, seed[1] - y
    keep = lab == lab[sy, sx]
    # fill holes
    filled = keep.astype(np.uint8)
    inv = 1 - filled
    n2, lab2, stats2, _ = cv2.connectedComponentsWithStats(inv, 4)
    for i in range(1, n2):
        bx, by, bw, bh, area = stats2[i]
        if bx > 0 and by > 0 and bx + bw < w and by + bh < h:
            filled[lab2 == i] = 1
    if erode:
        filled = cv2.erode(filled, np.ones((3, 3), np.uint8), iterations=erode)
    alpha = cv2.GaussianBlur(filled.astype(np.float32), (0, 0), 0.8)
    # unmix the grey fringe
    a3 = np.clip(alpha, 1e-3, 1)[..., None]
    rgb = np.clip((rgb - grey * (1 - a3)) / a3, 0, 1)
    return rgb, alpha


def trim(rgb, alpha, pad=4):
    ys, xs = np.where(alpha > 0.02)
    y0, y1 = max(0, ys.min() - pad), min(alpha.shape[0], ys.max() + pad + 1)
    x0, x1 = max(0, xs.min() - pad), min(alpha.shape[1], xs.max() + pad + 1)
    return rgb[y0:y1, x0:x1], alpha[y0:y1, x0:x1], (x0, y0)


