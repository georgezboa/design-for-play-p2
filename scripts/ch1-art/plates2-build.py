def write_js(name, title, consts):
    lines = [
        f'// GENERATED by scripts/ch1-art/plates2-build.py — do not edit by hand.',
        f'// {title}: plate URLs and the painted objects\' boxes, measured on the',
        '// processed plates (tile-normalised [x, y, w, h] / [u, v]).',
        '',
    ]
    def plain(o):
        if isinstance(o, dict):
            return {k: plain(v) for k, v in o.items()}
        if isinstance(o, (list, tuple)):
            return [plain(v) for v in o]
        if isinstance(o, (np.floating, float)):
            return round(float(o), 4)
        if isinstance(o, np.integer):
            return int(o)
        return o
    for key, value in consts.items():
        lines.append(f'export const {key} = Object.freeze({json.dumps(plain(value))});')
    (JS / name).write_text('\n'.join(lines) + '\n')
    print(f'  wrote src/chapters/nightService/art/{name}')


