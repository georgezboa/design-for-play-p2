def text_layer(w, h, lines, *, pad=0.08, tracking=0.08, align='center', margin=0.5):
    """Render lines [(text, fontname, rel_size, (r, g, b))] in a w×h slot (4× supersampled).
    Sizes are set by cap height, so descenders (J, g) hang into the margin
    instead of being clipped; the canvas is h·(1 + 2·margin) tall."""
    S = 4
    W = w * S
    slot = h * S
    mh = int(slot * margin)
    H = slot + 2 * mh
    canvas = Image.new('RGBA', (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(canvas)
    total = sum(rel for _, _, rel, _ in lines)
    gap = 0.32
    avail_h = slot * (1 - 2 * pad) / (1 + gap * (len(lines) - 1) / max(1, len(lines)))
    avail_w = W * (1 - 2 * pad)
    rendered = []
    for text, fname, rel, color in lines:
        cap_want = avail_h * rel / total
        size = max(8, int(cap_want / 0.7))
        while True:
            f = font(fname, size)
            cap = f.getbbox('H', anchor='ls')
            cap_h = -cap[1]
            if cap_h > cap_want and size > 8:
                size = int(size * cap_want / cap_h)
                continue
            widths = [f.getlength(ch) for ch in text]
            track = size * tracking
            tw = sum(widths) + track * (len(text) - 1)
            if tw <= avail_w or size < 8:
                break
            size = int(size * 0.95)
        rendered.append((text, f, -f.getbbox('H', anchor='ls')[1], color, widths, track, tw))
    block = sum(r[2] for r in rendered) + gap * sum(r[2] for r in rendered[:-1])
    y = mh + (slot - block) / 2
    for text, f, cap_h, color, widths, track, tw in rendered:
        x = (W - tw) / 2 if align == 'center' else W * pad
        base = y + cap_h
        for ch, cw in zip(text, widths):
            d.text((x, base), ch, font=f, fill=(*color, 255), anchor='ls')
            x += cw + track
        y = base + cap_h * gap
    return canvas.resize((w, h + 2 * int(h * margin)), Image.LANCZOS), int(h * margin)


def paint_text(img, quad, lines, *, opacity=0.88, grain=0.5, blur=0.5, tracking=0.08, pad=0.1, align='center'):
    """Paint words onto a plate as if lettered on it: fitted to the quad's
    perspective, softened, and broken up by the surface underneath."""
    quad = np.float32(quad)
    w = int(max(np.linalg.norm(quad[1] - quad[0]), np.linalg.norm(quad[2] - quad[3])))
    h = int(max(np.linalg.norm(quad[3] - quad[0]), np.linalg.norm(quad[2] - quad[1])))
    im, m = text_layer(w, h, lines, tracking=tracking, pad=pad, align=align)
    layer = np.asarray(im, dtype=np.float32) / 255
    M = cv2.getPerspectiveTransform(np.float32([[0, m], [w, m], [w, h + m], [0, h + m]]), quad)
    out = cv2.warpPerspective(layer, M, (img.shape[1], img.shape[0]), flags=cv2.INTER_LINEAR)
    color, alpha = out[..., :3], out[..., 3]
    if blur:
        alpha = cv2.GaussianBlur(alpha, (0, 0), blur)
    # the enamel's own grain shows through the paint
    base = luma(img)
    hi = cv2.GaussianBlur(base, (0, 0), 3)
    tex = np.clip(1 - grain * np.abs(base - hi) * 6, 0.3, 1)
    a = alpha * opacity * tex
    # paint takes the light that falls on the plate
    light = np.clip(cv2.GaussianBlur(base, (0, 0), 25) / max(1e-3, np.percentile(base[alpha > 0.5], 90) if (alpha > 0.5).any() else 1), 0.35, 1.0)
    return over(img, color * light[..., None], a)


