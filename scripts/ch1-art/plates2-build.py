# geometry → tile coordinates

def tbox(box, cb):
    """Source box (x, y, w, h) → tile-normalised [u, v, w, h] in crop cb."""
    x, y, w, h = box
    return [round((x - cb[0]) / cb[2], 4), round((y - cb[1]) / cb[3], 4), round(w / cb[2], 4), round(h / cb[3], 4)]


def tpt(pt, cb):
    return [round((pt[0] - cb[0]) / cb[2], 4), round((pt[1] - cb[1]) / cb[3], 4)]


def zoom_square(box, cb, pad=1.15, fit=True):
    """A zoom rect (w == h in tile units, i.e. the tile's own aspect) around a source box."""
    u, v, w, h = tbox(box, cb)
    s = min(1.0, max(w, h) * pad)
    cx, cy = u + w / 2, v + h / 2
    x0, y0 = cx - s / 2, cy - s / 2
    if fit:
        x0 = min(max(0, x0), 1 - s)
        y0 = min(max(0, y0), 1 - s)
    return [round(x0, 4), round(y0, 4), round(s, 4), round(s, 4)]


