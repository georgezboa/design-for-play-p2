# small image kit (float RGB in 0..1, HxWx3; alpha HxW)

def src_path(name):
    return Path(ARGS.src) / f'{name}.png'


def load(name):
    with Image.open(src_path(name)) as im:
        return np.asarray(im.convert('RGB'), dtype=np.float32) / 255


def load_rgba(path):
    with Image.open(path) as im:
        a = np.asarray(im.convert('RGBA'), dtype=np.float32) / 255
    return a[..., :3], a[..., 3]


def crop(img, box):
    x, y, w, h = box
    return img[y:y + h, x:x + w].copy()


def resize(img, w, h):
    return cv2.resize(img, (int(w), int(h)), interpolation=cv2.INTER_AREA if w < img.shape[1] else cv2.INTER_LANCZOS4)


def to_u8(img):
    return np.clip(img * 255 + 0.5, 0, 255).astype(np.uint8)


def luma(img):
    return img[..., 0] * 0.2126 + img[..., 1] * 0.7152 + img[..., 2] * 0.0722


def over(dst, src, alpha):
    a = alpha[..., None]
    return dst * (1 - a) + src * a


def smooth(x):
    x = np.clip(x, 0, 1)
    return x * x * (3 - 2 * x)


def rrect_alpha(shape, box, r, feather=1.2):
    """Soft rounded-rectangle coverage (signed distance)."""
    h, w = shape[:2]
    x, y, bw, bh = box
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    cx, cy = x + bw / 2, y + bh / 2
    qx = np.abs(xx + 0.5 - cx) - (bw / 2 - r)
    qy = np.abs(yy + 0.5 - cy) - (bh / 2 - r)
    d = np.hypot(np.maximum(qx, 0), np.maximum(qy, 0)) + np.minimum(np.maximum(qx, qy), 0) - r
    return np.clip(0.5 - d / feather, 0, 1)


def radial(shape, cx, cy, r, power=1.0):
    h, w = shape[:2]
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    d = np.hypot(xx - cx, yy - cy) / r
    return np.clip(1 - d, 0, 1) ** power


