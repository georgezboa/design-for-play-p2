_ERA = {}


def fit_era(pairs):
    """Learn George's present → 1978 colour shift from registered pairs (quadratic colour map)."""
    X, Y = [], []
    rng = np.random.default_rng(1978)
    for a, b in pairs:
        idx = rng.choice(a.shape[0] * a.shape[1], 60000, replace=False)
        pa = a.reshape(-1, 3)[idx]
        pb = b.reshape(-1, 3)[idx]
        X.append(pa)
        Y.append(pb)
    X = np.concatenate(X)
    Y = np.concatenate(Y)

    def feats(p):
        r, g, b = p[:, 0], p[:, 1], p[:, 2]
        return np.stack([np.ones_like(r), r, g, b, r * r, g * g, b * b, r * g, g * b, r * b], 1)

    F = feats(X)
    coef = np.linalg.lstsq(F, Y, rcond=None)[0]
    # one robust pass: drop the pixels that changed for real (tags, the push plate)
    err = np.linalg.norm(F @ coef - Y, axis=1)
    ok = err < np.percentile(err, 85)
    coef = np.linalg.lstsq(F[ok], Y[ok], rcond=None)[0]
    _ERA['coef'] = coef
    _ERA['feats'] = feats
    print(f'  1978 grade fitted on {ok.sum()} pixels (rms {np.sqrt((err[ok] ** 2).mean()):.3f})')


def era_1978(img):
    p = img.reshape(-1, 3)
    out = _ERA['feats'](p) @ _ERA['coef']
    return np.clip(out.reshape(img.shape), 0, 1)


def paper_grain(img, k):
    with Image.open(PAPER) as im:
        paper = np.asarray(im.convert('L'), dtype=np.float32) / 255
    reps = (math.ceil(img.shape[0] / paper.shape[0]), math.ceil(img.shape[1] / paper.shape[1]))
    paper = np.tile(paper, reps)[:img.shape[0], :img.shape[1]]
    paper = paper / paper.mean()
    noise = np.random.default_rng(11).normal(1, 0.035, img.shape[:2]).astype(np.float32)
    noise = cv2.GaussianBlur(noise, (0, 0), 0.7)
    return np.clip(img * (1 + (paper * noise - 1) * k)[..., None], 0, 1)


