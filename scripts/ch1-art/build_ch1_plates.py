def norm(plate, anchor):
    x0, y0, w, h = plate['crop']
    kind, *v = anchor
    r = lambda n: round(n, 4)
    if kind == 'y':
        return r((v[0] - y0) / h)
    if kind == 'x':
        return r((v[0] - x0) / w)
    if kind == 'pt':
        return [r((v[0] - x0) / w), r((v[1] - y0) / h)]
    if kind == 'rect':
        return [r((v[0] - x0) / w), r((v[1] - y0) / h), r((v[2] - v[0]) / w), r((v[3] - v[1]) / h)]
    if kind == 'r':
        return r(v[0] / w)
    if kind == 'quad':
        return [r((v[i] - x0) / w) if i % 2 == 0 else r((v[i] - y0) / h) for i in range(8)]
    raise ValueError(kind)


def solve_box(pairs, child_crop):
    """Least squares for the box (bx, by, bw) in parent px: P = B + c * (bw, bw / ASPECT)."""
    cx0, cy0, cw, ch = child_crop
    rows = []
    for (px, py), (sx, sy) in pairs:
        u = (sx - cx0) / cw
        v = (sy - cy0) / ch
        rows.append((1, 0, u, px))
        rows.append((0, 1, v / ASPECT, py))
    # normal equations, 3 unknowns
    ata = [[0.0] * 3 for _ in range(3)]
    atb = [0.0] * 3
    for a0, a1, a2, b in rows:
        a = (a0, a1, a2)
        for i in range(3):
            atb[i] += a[i] * b
            for j in range(3):
                ata[i][j] += a[i] * a[j]
    # Gaussian elimination
    m = [ata[i] + [atb[i]] for i in range(3)]
    for i in range(3):
        p = max(range(i, 3), key=lambda k: abs(m[k][i]))
        m[i], m[p] = m[p], m[i]
        for k in range(i + 1, 3):
            f = m[k][i] / m[i][i]
            m[k] = [m[k][j] - f * m[i][j] for j in range(4)]
    x = [0.0] * 3
    for i in (2, 1, 0):
        x[i] = (m[i][3] - sum(m[i][j] * x[j] for j in range(i + 1, 3))) / m[i][i]
    return x


def solve_pinned_right(xpairs, ypairs, child_crop, parent_crop):
    """Least squares for a box whose right edge is the parent's: x pairs fix its width, y pairs its top."""
    cx0, cy0, cw, ch = child_crop
    right = parent_crop[0] + parent_crop[2]
    # px = right - (1 - u) * bw  ->  (right - px) = (1 - u) * bw
    num = sum((1 - (sx - cx0) / cw) * (right - px) for px, sx in xpairs)
    den = sum((1 - (sx - cx0) / cw) ** 2 for px, sx in xpairs)
    bw = num / den
    by = sum(py - ((sy - cy0) / ch) * bw / ASPECT for py, sy in ypairs) / len(ypairs)
    return right - bw, by, bw


def zoom_rect(child_id):
    z = ZOOMS[child_id]
    parent = PLATE_BY_ID[z['parent']]
    child = PLATE_BY_ID[child_id]
    if 'box' in z:
        bx, by, bw = z['box']
    elif z.get('pin') == 'right':
        bx, by, bw = solve_pinned_right(z['xpairs'], z['ypairs'], child['crop'], parent['crop'])
    elif 'lamp' in z:
        # one point held still (parent px <-> child px) at a chosen box width
        (px, py), (sx, sy) = z['lamp']
        bw = z['width']
        cx0, cy0, cw, ch = child['crop']
        bx = px - (sx - cx0) / cw * bw
        by = py - (sy - cy0) / ch * bw / ASPECT
    else:
        bx, by, bw = solve_box(z['pairs'], child['crop'])
    x0, y0, w, h = parent['crop']
    u = (bx - x0) / w
    v = (by - y0) / h
    s = bw / w
    return [round(u, 4), round(v, 4), round(s, 4), round(s, 4)]


