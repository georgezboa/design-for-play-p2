def crop_plate(src_dir, plate):
    im = Image.open(os.path.join(src_dir, plate['src'])).convert('RGB')
    x0, y0, w, h = plate['crop']
    if x0 < -0.5 or y0 < -0.5 or x0 + w > SRC_W + 0.5 or y0 + h > SRC_H + 0.5:
        raise SystemExit(f"{plate['id']}: crop {plate['crop']} leaves the {plate['src']} source")
    return im.resize((OUT_W, OUT_H), Image.LANCZOS, box=(x0, y0, x0 + w, y0 + h))


def cut_prop(src_dir, prop):
    im = Image.open(os.path.join(src_dir, prop['src'])).convert('RGB').crop(prop['box'])
    r, g, b = im.split()
    # distance from the flat grey ground (122, 122, 123)
    grey = Image.new('RGB', im.size, (122, 122, 123))
    diff = ImageChops.difference(im, grey).convert('L').point(lambda d: 255 if d > 20 else 0)
    # the props themselves are coloured (brass, paper, twine); the hatched
    # shadows are grey ink: keep colour, and the ink within a few px of it
    sat = im.convert('HSV').split()[1].point(lambda s: 255 if s > 48 else 0)
    near = sat.filter(ImageFilter.MaxFilter(7))
    alpha = ImageChops.multiply(near, diff).filter(ImageFilter.GaussianBlur(0.7))
    out = im.copy()
    out.putalpha(alpha)
    bbox = alpha.point(lambda a: 255 if a > 8 else 0).getbbox()
    out = out.crop(bbox)
    if prop.get('scale', 1) != 1:
        out = out.resize((round(out.width * prop['scale']), round(out.height * prop['scale'])), Image.LANCZOS)
    return out


