"""The painted cutscenes (round 9): George's paintings → runtime plates.

    python3 -I scripts/cutscene-art/build.py [--src DIR] [--ch1 DIR] [--standins] [--only ID,ID]

Reads the read-only 1536×1024 sources: the cutscene batch
(NIGHTFALL art/cutscenes/, default /home/claude/art-src/cutscenes or
$NIGHTFALL_CUTSCENE_SRC) and the Chapter 1 paintings the cutscenes reuse
(/home/claude/art-src/ch1 or $NIGHTFALL_ART_SRC). Writes

  public/assets/cutscenes/<id>.webp        the stage plates, 2 : 1 (1536 × 768),
                                           green window glass keyed to alpha
  public/assets/cutscenes/ASSET_MANIFEST.md
  scripts/cutscene-art/manifest.json       crops, keys, links, pair alignment
  src/shell/cutscene/painted/plates.generated.js
                                           URLs, sizes, the glass rect of every
                                           window plate, the solved rect of every
                                           close-up inside its parent (stage units),
                                           and which cutscenes are complete

A plate whose painting is not in yet is built from a STAND-IN (another
painting, cropped), marked `standIn`, so the scenes can be developed and
reviewed (`?cutscenes=painted`); a cutscene plays painted in the game only
when none of its plates is a stand-in. When George replaces a painting, run
this again: crops, keys, links and alignment follow.

Needs Python 3 with Pillow, numpy and OpenCV.
"""

