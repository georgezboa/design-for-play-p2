def load_batch():
    if BATCH.exists():
        return json.loads(BATCH.read_text())
    return {'items': []}


def band_crop(img, frac):
    w, h = img.size
    want = round(w / 2)
    if h <= want:
        return img, (0, 0, w, h)
    top = round((h - want) * frac)
    box = (0, top, w, top + want)
    return img.crop(box), box


def key_green(rgb):
    """Pure #00FF00 glass → alpha, with the green spill taken off the edges."""
    a = rgb.astype(np.float32)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    greenness = g - np.maximum(r, b)
    alpha = 1.0 - np.clip((greenness - 60.0) / 90.0, 0.0, 1.0)
    # despill near the key
    spill = (greenness > 18) & (alpha > 0)
    g2 = np.where(spill, np.minimum(g, np.maximum(r, b) + 10), g)
    out = np.dstack([r, g2, b, alpha * 255.0]).clip(0, 255).astype(np.uint8)
    keyed = alpha < 0.5
    if keyed.any():
        ys, xs = np.where(keyed)
        glass = [int(xs.min()), int(ys.min()), int(xs.max() - xs.min() + 1), int(ys.max() - ys.min() + 1)]
    else:
        glass = None
    return out, glass, float(keyed.mean())


def key_grey(rgb, tol=26):
    """A cut-out on flat mid-grey (#7F7F7F) → alpha, trimmed."""
    a = rgb.astype(np.int16)
    d = np.abs(a - 127).max(axis=2)
    alpha = np.clip((d - tol) / 18.0, 0, 1)
    alpha = cv2.GaussianBlur(alpha.astype(np.float32), (3, 3), 0)
    out = np.dstack([rgb, (alpha * 255).astype(np.uint8)])
    ys, xs = np.where(alpha > 0.1)
    if len(xs):
        x0, x1, y0, y1 = max(0, xs.min() - 6), min(rgb.shape[1], xs.max() + 7), max(0, ys.min() - 6), min(rgb.shape[0], ys.max() + 7)
        out = out[y0:y1, x0:x1]
    return out


def solve_link(child, parent):
    """Where the child (a close-up) sits in the parent: a rect in parent px, or None."""
    g1 = cv2.cvtColor(np.array(child.convert('RGB')), cv2.COLOR_RGB2GRAY)
    g2 = cv2.cvtColor(np.array(parent.convert('RGB')), cv2.COLOR_RGB2GRAY)
    det = cv2.AKAZE_create()
    k1, d1 = det.detectAndCompute(g1, None)
    k2, d2 = det.detectAndCompute(g2, None)
    if d1 is None or d2 is None or len(k1) < 12 or len(k2) < 12:
        return None, 0
    m = cv2.BFMatcher(cv2.NORM_HAMMING).knnMatch(d1, d2, k=2)
    good = [a for a, b in (p for p in m if len(p) == 2) if a.distance < 0.78 * b.distance]
    if len(good) < 12:
        return None, len(good)
    src = np.float32([k1[g.queryIdx].pt for g in good]).reshape(-1, 1, 2)
    dst = np.float32([k2[g.trainIdx].pt for g in good]).reshape(-1, 1, 2)
    H, inl = cv2.findHomography(src, dst, cv2.RANSAC, 6.0)
    if H is None or inl.sum() < 10:
        return None, int(inl.sum()) if inl is not None else 0
    h, w = g1.shape
    corners = cv2.perspectiveTransform(np.float32([[0, 0], [w, 0], [w, h], [0, h]]).reshape(-1, 1, 2), H).reshape(-1, 2)
    x0, y0 = corners.min(axis=0)
    x1, y1 = corners.max(axis=0)
    # keep the stage aspect, about the solved centre
    cx, cy, rw = (x0 + x1) / 2, (y0 + y1) / 2, max(x1 - x0, (y1 - y0) * 2)
    return [float(cx - rw / 2), float(cy - rw / 4), float(rw), float(rw / 2)], int(inl.sum())


def align_pair(a, b):
    """Warp b onto a (the edit tool may shift a picture a few px): ECC affine on a small copy."""
    ga = cv2.cvtColor(np.array(a.convert('RGB')), cv2.COLOR_RGB2GRAY).astype(np.float32) / 255
    gb = cv2.cvtColor(np.array(b.convert('RGB')), cv2.COLOR_RGB2GRAY).astype(np.float32) / 255
    s = 0.25
    sa = cv2.resize(ga, None, fx=s, fy=s, interpolation=cv2.INTER_AREA)
    sb = cv2.resize(gb, None, fx=s, fy=s, interpolation=cv2.INTER_AREA)
    warp = np.eye(2, 3, dtype=np.float32)
    try:
        cc, warp = cv2.findTransformECC(sa, sb, warp, cv2.MOTION_AFFINE, (cv2.TERM_CRITERIA_EPS | cv2.TERM_CRITERIA_COUNT, 200, 1e-5), None, 5)
    except cv2.error:
        return b, None
    warp[:, 2] /= s
    shift = float(np.hypot(warp[0, 2], warp[1, 2]))
    if shift < 0.75 and abs(warp[0, 0] - 1) < 0.002:
        return b, {'cc': round(float(cc), 4), 'shift': round(shift, 2), 'warped': False}
    arr = np.array(b)
    out = cv2.warpAffine(arr, warp, (arr.shape[1], arr.shape[0]), flags=cv2.INTER_CUBIC | cv2.WARP_INVERSE_MAP, borderMode=cv2.BORDER_REPLICATE)
    return Image.fromarray(out), {'cc': round(float(cc), 4), 'shift': round(shift, 2), 'warped': True, 'warp': [[round(float(v), 5) for v in row] for row in warp]}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--src', default=os.environ.get('NIGHTFALL_CUTSCENE_SRC', '/home/claude/art-src/cutscenes'))
    ap.add_argument('--ch1', default=os.environ.get('NIGHTFALL_ART_SRC', '/home/claude/art-src/ch1'))
    ap.add_argument('--st', default=os.environ.get('NIGHTFALL_STYLE_SRC', '/home/claude/art-src/style-tests'))
    ap.add_argument('--standins', action='store_true', help='build stand-ins for paintings not in yet')
    ap.add_argument('--only', default='')
    args = ap.parse_args()
    src = Path(args.src)
    dirs = {'cut': src, 'ch1': Path(args.ch1), 'st': Path(args.st)}
    batch = load_batch()
    items = {it['id']: it for it in batch.get('items', [])}
    ids = REUSED + list(items)
    if args.only:
        keep = set(args.only.split(','))
        ids = [i for i in ids if i in keep]
    OUT.mkdir(parents=True, exist_ok=True)
    old = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}
    plates = dict(old.get('plates', {}))
    cropped = {}
    for pid in ids:
        it = items.get(pid, {})
        path = (dirs['ch1'] / f'{pid}.png') if pid in REUSED else (src / f'{pid}.png')
        stand = None
        if not path.exists():
            if not args.standins or pid not in STANDINS:
                if pid not in plates:
                    plates[pid] = {'missing': True}
                continue
            key, name, box, treat = STANDINS[pid]
            path = dirs[key] / name
            stand = {'from': name, 'box': box, 'treat': treat}
        img = Image.open(path).convert('RGB')
        if stand and stand['box']:
            x0, y0, x1, y1 = stand['box']
            img = img.crop((x0, y0, x1, y1)).resize((1536, 1024), Image.LANCZOS)
        treat = stand and stand['treat']
        if treat == 'older':
            img = Image.blend(img, ImageOps.colorize(ImageOps.grayscale(img), '#1c140c', '#e6d2a8'), 0.45)
        elif treat == 'dark':
            img = Image.eval(img, lambda v: int(v * 0.45))
        elif treat == 'dusk':
            img = Image.blend(img, ImageOps.colorize(ImageOps.grayscale(img), '#1a0c06', '#ffb066'), 0.5)
        elif treat == 'grey':
            img = Image.blend(img, ImageOps.colorize(ImageOps.grayscale(img), '#5a5a58', '#c8c6c0'), 0.85)
        elif treat in ('pencil', 'paper'):
            g = cv2.cvtColor(np.array(img), cv2.COLOR_RGB2GRAY)
            inv = 255 - cv2.GaussianBlur(255 - g, (21, 21), 0)
            sketch = cv2.divide(g, inv, scale=256)
            paper = np.dstack([np.full_like(sketch, 239), np.full_like(sketch, 230), np.full_like(sketch, 210)]).astype(np.float32)
            out = paper * (sketch[..., None].astype(np.float32) / 255)
            if treat == 'paper':
                out = 0.55 * out + 0.45 * np.array(img).astype(np.float32) * 1.4
            img = Image.fromarray(out.clip(0, 255).astype(np.uint8))
        elif treat == 'black':
            arr = np.array(img).astype(np.float32)
            grey = (np.abs(arr - 127).max(axis=2) < 26)
            arr[~grey] = arr[~grey] * 0.12
            img = Image.fromarray(arr.clip(0, 255).astype(np.uint8))
        if img.size != (1536, 1024):
            img = img.resize((1536, round(1536 * img.size[1] / img.size[0])), Image.LANCZOS)
        sheet = it.get('style') == 'sheet'
        entry = {'source': path.name, 'standIn': stand}
        if sheet:
            arr = key_grey(np.array(img))
            out = Image.fromarray(arr, 'RGBA')
            entry.update({'kind': 'cutout', 'size': list(out.size)})
        else:
            part, box = band_crop(img, BAND.get(pid, 0.5))
            part = part.resize((OUT_W, OUT_H), Image.LANCZOS)
            entry.update({'kind': 'plate', 'crop': list(box), 'size': [OUT_W, OUT_H]})
            green = it.get('chroma_window') or pid in GREEN_ITEMS_FALLBACK
            if green and not stand:
                arr, glass, frac = key_green(np.array(part))
                out = Image.fromarray(arr, 'RGBA')
                k = STAGE[0] / OUT_W
                entry.update({'glass': [round(v * k, 1) for v in glass] if glass else None, 'keyed': round(frac, 4)})
            else:
                out = part
            cropped[pid] = part
            pair = it.get('pair_of') or EXTRA_PAIRS.get(pid)
            if pair and pair in cropped and not stand:
                aligned, info = align_pair(cropped[pair], part)
                entry['align'] = info
                if info and info.get('warped'):
                    out = aligned if out.mode == 'RGB' else out
        # stand-ins go to a git-ignored folder: they never ship
        name = f'standin/{pid}.webp' if stand else f'{pid}.webp'
        (OUT / name).parent.mkdir(parents=True, exist_ok=True)
        if not stand and (OUT / 'standin' / f'{pid}.webp').exists():
            (OUT / 'standin' / f'{pid}.webp').unlink()
        out.save(OUT / name, 'WEBP', quality=QUALITY, method=6)
        entry.update({'url': f'{URL}/{name}', 'bytes': (OUT / name).stat().st_size})
        plates[pid] = entry
        print(f'{pid:18s} {"stand-in " if stand else ""}{entry.get("kind")} {entry["bytes"] // 1024} KB')

    # close-ups inside their parents
    links = {}
    k = STAGE[0] / OUT_W
    for child, parent in LINKS.items():
        rect, quality = None, 0
        if child in cropped and parent in cropped and not plates.get(child, {}).get('standIn') and not plates.get(parent, {}).get('standIn'):
            rect, quality = solve_link(cropped[child], cropped[parent])
        if rect:
            links[child] = {'parent': parent, 'rect': [round(v * k, 1) for v in rect], 'inliers': quality, 'solved': True}
        elif child in FALLBACK_LINKS:
            links[child] = {'parent': parent, 'rect': FALLBACK_LINKS[child], 'inliers': quality, 'solved': False}

    # which cutscenes are complete (no stand-in, nothing missing)
    needs = {}
    for b in batch.get('storyboard', []):
        want = sorted({p for s in b['shots'] for p in s['plates'] if p in items or p in REUSED})
        needs[b['id']] = want
    complete = {cid: all(plates.get(p, {}).get('url') and not plates[p].get('standIn') for p in want) for cid, want in needs.items()}

    manifest = {'generator': 'scripts/cutscene-art/build.py', 'stage': STAGE, 'plates': plates, 'links': links, 'complete': complete}
    MANIFEST.write_text(json.dumps(manifest, indent=1))
    js_plates = {pid: {k2: v for k2, v in e.items() if k2 in ('url', 'size', 'glass', 'kind')} | ({'standIn': True} if e.get('standIn') else {})
                 for pid, e in sorted(plates.items()) if e.get('url')}
    JS.parent.mkdir(parents=True, exist_ok=True)
    def rows(d):
        return '{\n' + ',\n'.join(f'  {json.dumps(k)}: {json.dumps(v, separators=(", ", ": "))}' for k, v in d.items()) + '\n}'
    JS.write_text('// Generated by scripts/cutscene-art/build.py: do not edit.\n'
                  '// The painted cutscenes\' plates (public/assets/cutscenes), their window glass and close-up rects in stage units\n'
                  '// (1600 × 800), and which cutscenes have every painting in (the others keep their round-6 drawing).\n'
                  f'export const PLATES = Object.freeze({rows(js_plates)});\n'
                  f'export const LINKS = Object.freeze({rows(links)});\n'
                  f'export const COMPLETE = Object.freeze({rows(complete)});\n')
    # the manifest beside the assets
    lines = ['# Painted cutscene plates', '', f'Built by `scripts/cutscene-art/build.py`. Paintings {CREDIT}; directed by George Zhong.', '',
             '| Plate | Source | Crop (source px) | Notes |', '|---|---|---|---|']
    for pid, e in sorted(plates.items()):
        if not e.get('url'):
            continue
        note = f"stand-in from {e['standIn']['from']}" if e.get('standIn') else ('cut-out on grey' if e.get('kind') == 'cutout' else ('green glass keyed' if e.get('glass') else ''))
        lines.append(f"| {pid}.webp | {e['source']} | {e.get('crop', '')} | {note} |")
    (OUT / 'ASSET_MANIFEST.md').write_text('\n'.join(lines) + '\n')
    total = sum(e.get('bytes', 0) for e in plates.values())
    print(f'{len([p for p in plates.values() if p.get("url")])} plates, {total / 1e6:.1f} MB; complete: {[c for c, v in complete.items() if v]}')


if __name__ == '__main__':
    sys.exit(main())
