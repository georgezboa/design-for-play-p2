  assert.match(scene, /paintWall\(tex\.getContext\(\), layout, \{ paper, chrome, low \}\);/);
  assert.match(scene, /-painted\$\{chrome\.bezel && chrome\.walnut \? '' : '-flat'\}\$\{low \? '-low' : ''\}/);
