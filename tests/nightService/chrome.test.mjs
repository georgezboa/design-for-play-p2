  assert.match(scene, /preload\(\) \{\s*this\.preloadChrome\(\);/);
  assert.match(scene, /preloadChrome\(\) \{\s*Object\.values\(CHROME_TEXTURES\)\.forEach\(\(\{ key, url \}\) => \{ if \(!this\.textures\.exists\(key\)\) this\.load\.image\(key, url\); \}\);/);
