/** Canvas size of a WebP (VP8X, VP8L or VP8). */
function webpSize(buf) {
  assert.equal(buf.toString('ascii', 0, 4), 'RIFF');
  assert.equal(buf.toString('ascii', 8, 12), 'WEBP');
  const kind = buf.toString('ascii', 12, 16);
  if (kind === 'VP8X') return [1 + buf.readUIntLE(24, 3), 1 + buf.readUIntLE(27, 3)];
  if (kind === 'VP8L') {
    const bits = buf.readUInt32LE(21);
    return [1 + (bits & 0x3fff), 1 + ((bits >> 14) & 0x3fff)];
  }
  return [buf.readUInt16LE(26) & 0x3fff, buf.readUInt16LE(28) & 0x3fff];
}

test('chrome assets: the bezel atlas and the walnut tile are built, small, and agree with wallArt.js', () => {
  const json = JSON.parse(readFileSync(pub(`${CHROME_DIR}/chrome.json`), 'utf8'));
  assert.deepEqual(json.size, [...CHROME_ATLAS.size], 'atlas size: rerun chrome-build.py, then copy chrome.json into CHROME_ATLAS');
  assert.equal(json.T, CHROME_ATLAS.T);
  for (const key of ['size', 'feather', 'innerRadius']) assert.equal(json.corner[key], CHROME_ATLAS.corner[key], `corner.${key}`);
  for (const key of ['tl', 'tr', 'bl', 'br']) assert.deepEqual(json.corner[key], [...CHROME_ATLAS.corner[key]], `corner.${key}`);
  assert.equal(json.rivet.size, CHROME_ATLAS.rivet.size);
  assert.deepEqual(json.rivet.at, CHROME_ATLAS.rivet.at.map((at) => [...at]));
  assert.deepEqual(json.strip, { ...CHROME_ATLAS.strip });
  assert.deepEqual(json.walnut.size, [...CHROME_ATLAS.walnut.size]);
  // the pieces fit the atlas: corners and screws on the top row, the strip under them
  const { corner, rivet, strip, size, T } = CHROME_ATLAS;
  assert.equal(strip.h, T, 'the strip is one band thick');
  assert.equal(strip.y, corner.size);
  assert.ok(strip.x + strip.w <= size[0] && strip.y + strip.h <= size[1]);
  rivet.at.forEach(([x, y]) => assert.ok(x + rivet.size <= size[0] && y + rivet.size <= corner.size));
  assert.ok(corner.feather > 0 && corner.feather < corner.size / 3);
  // the files, and what they weigh
  assert.deepEqual(webpSize(readFileSync(pub(CHROME_TEXTURES.bezel.url))), [...CHROME_ATLAS.size]);
  assert.deepEqual(webpSize(readFileSync(pub(CHROME_TEXTURES.walnut.url))), [...CHROME_ATLAS.walnut.size]);
  const bytes = Object.values(CHROME_TEXTURES).reduce((sum, { url }) => sum + statSync(pub(url)).size, 0);
  assert.ok(bytes < 200 * 1024, `the chrome stays light (${bytes} bytes)`);
  assert.ok(CHROME_TEXTURES.bezel.url.startsWith('/assets/ch1-painted/chrome/'));
  // regenerable, and credited
  const script = read('scripts/ch1-art/chrome-build.py');
  assert.match(script, /C-bezel\.png/);
  assert.match(script, /'public', 'assets', 'ch1-painted', 'chrome'/);
  const manifest = read('public/assets/ch1-painted/chrome/ASSET_MANIFEST.md');
  assert.match(manifest, /C-bezel\.png/);
  assert.match(manifest, /generated by George with ChatGPT\/Codex image generation \(OpenAI\), 2026-10-08/i);
});

test('chrome geometry: the bezel band (and so its drag hit area) is unchanged; the hole follows the painted ring', () => {
  assert.equal(BEZEL, 13, 'the round-6 bezel band: bezelSlotAt and unfoldLayout depend on it');
  assert.ok(BEZEL_LIP > 0 && BEZEL_LIP < 3, 'the painted band only just covers the picture edge');
  assert.ok(RADIUS >= 16 && RADIUS <= 26, `the hole's corner (${RADIUS}) is the ring's own inner curve`);
  layouts().forEach(([id, layout]) => {
    const k = layout.scale ?? 1;
    assert.equal(bezelPad(layout), Math.max(6, (13 + 6) * k), `${id}: the bezel band you can take hold of`);
    const a = layout.slots[0];
    assert.equal(bezelSlotAt(layout, a.x + a.w / 2, a.y - 6 * k)?.index, 0, `${id}: the bezel over the first window moves it`);
  });
});

test('chrome wall: a lamp over every gutter and both ends, the sill where the captions expect it, room round the trim', () => {
  layouts().forEach(([id, layout]) => {
    const geo = wallGeometry(layout);
    const k = layout.scale ?? 1;
    assert.equal(geo.lamps.length, layout.cols + 1, `${id}: lamps`);
    geo.lamps.slice(1, -1).forEach((lamp, i) => assert.equal(lamp.x, layout.slots[i + 1].x - layout.gutter / 2, `${id}: lamp over gutter ${i}`));
    assert.ok(geo.lamps[0].x < layout.x && geo.lamps.at(-1).x > layout.x + layout.w);
    if (k === 1) assert.equal(geo.sillY, layout.y + layout.h + 34 + 22, `${id}: the round-6 sill height`);
    // a big window's bezel is wider on screen: the panel grows with it, so
    // the 9 px trim never crowds it
    assert.ok(geo.pad - 9 - BEZEL * k >= 11, `${id}: walnut between bezel and trim`);
    assert.ok(geo.gx >= 20 && geo.gx + geo.gw <= layout.view.w - 20, `${id}: the panel stays on screen`);
    assert.ok(geo.sillY + 8 < layout.view.h - 40, `${id}: the sill is on screen, under the windows`);
  });
  const act1 = createPanelModel(ACTS.act1, { carry: carry(ACTS.act1) }).layout;
  assert.equal(wallGeometry(act1, { painted: false }).pad, 34, 'the legacy wall keeps its pad');
});

