const root = new URL('../../', import.meta.url);
const read = (path) => readFileSync(new URL(path, root), 'utf8');
const publicFile = (url) => new URL(`public${url}`, root);
const PAINTED = ['act0', 'act05', 'act1'];
const RIG_H = 70; // Butch's rig height in tile px at scale 1 (actorRig.js)
const TILE_H = 414;

/** Every edge of a tile in a state, by side. */
const edgesOf = (act, tile, state) => ACTS[act].tiles[tile].states[state].edges ?? {};
const edgeAt = (act, tile, state, side, type) => (edgesOf(act, tile, state)[side] ?? []).find((e) => e.type === type)?.at;

test('round 7: every state of Acts 0, 0.5 and 1 has its painted plate, and the file is there', () => {
  for (const id of PAINTED) {
    for (const [tileId, tile] of Object.entries(ACTS[id].tiles)) {
      for (const [stateId, state] of Object.entries(tile.states)) {
        assert.equal(typeof state.plate, 'string', `${id} ${tileId}.${stateId} has a plate`);
        assert.match(state.plate, /^\/assets\/ch1-painted\/act(0|05|1)\/[\w-]+\.webp$/, `${id} ${tileId}.${stateId}`);
        assert.ok(existsSync(publicFile(state.plate)), `${state.plate} exists`);
      }
    }
    // and the preload names them all (the flag-chosen ones and the props too)
    const urls = actPlates(ACTS[id]).map((p) => p.url);
    for (const url of urls) assert.ok(existsSync(publicFile(url)), `${url} exists`);
  }
  // the props the acts animate: cut out with alpha
  for (const prop of Object.values(PROP)) {
    const buf = readFileSync(publicFile(prop.url));
    assert.equal(buf.toString('ascii', 0, 4), 'RIFF');
    assert.equal(buf.toString('ascii', 8, 12), 'WEBP');
    assert.ok(buf.includes(Buffer.from('ALPH')) || buf.toString('ascii', 12, 16) === 'VP8L', `${prop.url} carries alpha`);
  }
  assert.ok(actPlates(ACTS.act05).some((p) => p.url === PROP['props/key'].url), 'Act 0.5 preloads the key');
  assert.ok(actPlates(ACTS.act1).some((p) => p.url === PROP['props/tag'].url), 'Act 1 preloads the claim tag');
});

test('round 7: the painted assets are WebP at the 1.8:1 panel size, under budget, with a manifest', () => {
  let total = 0;
  for (const plate of Object.values(PLATE)) {
    const buf = readFileSync(publicFile(plate.url));
    total += buf.length;
    // VP8 (lossy) frame header: width / height at bytes 26..29
    assert.equal(buf.toString('ascii', 12, 16), 'VP8 ', plate.url);
    const w = buf.readUInt16LE(26) & 0x3fff;
    const h = buf.readUInt16LE(28) & 0x3fff;
    assert.deepEqual([w, h], [1536, 853], plate.url);
    // the crop is the panel's aspect, inside its 1536×1024 source
    const [x, y, cw, ch] = plate.crop;
    assert.ok(Math.abs(cw / ch - 1.8) < 0.002, `${plate.url} crop aspect`);
    assert.ok(x >= -0.5 && y >= -0.5 && x + cw <= 1536.5 && y + ch <= 1024.5, `${plate.url} crop inside the source`);
  }
  for (const prop of Object.values(PROP)) total += statSync(publicFile(prop.url)).size;
  assert.ok(total < 6e6, `Acts 0–1 plates stay small (${(total / 1e6).toFixed(2)} MB)`);
  const manifest = read('public/assets/ch1-painted/ASSET_MANIFEST.md');
  assert.match(manifest, /generated by George with ChatGPT\/Codex image generation \(OpenAI\), 2026-10-08/);
  for (const plate of Object.values(PLATE)) assert.ok(manifest.includes(plate.src), plate.src);
  assert.ok(existsSync(new URL('scripts/ch1-art/build_ch1_plates.py', root)), 'the script that regenerates them');
});

test('round 7: Act 0.5 edges sit on the painted lines; the floor and the close-ups\' wire meet', () => {
  const desk = ANCHOR['act05/desk'];
  const door = ANCHOR['act05/door-locked'];
  // desk right floor ↔ stores door left floor (every door state)
  const deskFloor = edgeAt('act05', 'desk', 'office', 'right', 'floor');
  assert.ok(Math.abs(deskFloor - desk.floorRight) < 1e-9, 'the desk edge is its painted floor');
  for (const state of ['locked', 'unlocked', 'open']) {
    const doorFloor = edgeAt('act05', 'door', state, 'left', 'floor');
    assert.ok(Math.abs(doorFloor - door.floorLeft) < 1e-9);
    assert.ok(Math.abs(doorFloor - deskFloor) <= 0.01, `floor meets (${state})`);
  }
  // the key line in the two close-ups: keys left ↔ lock right (the door stands left)
  const keys = edgeAt('act05', 'desk', 'keys', 'left', 'wire');
  const lock = edgeAt('act05', 'door', 'lock', 'right', 'wire');
  assert.ok(Math.abs(keys - ANCHOR['act05/keys'].wireLeft) < 1e-9 && Math.abs(lock - ANCHOR['act05/lock'].wireRight) < 1e-9);
  assert.ok(Math.abs(keys - lock) <= 0.01, `wire meets (${keys} / ${lock})`);
  // wide, the office's line and the door's never meet (that is the puzzle) …
  const deskWire = edgeAt('act05', 'desk', 'office', 'left', 'wire');
  const doorWire = edgeAt('act05', 'door', 'locked', 'right', 'wire');
  assert.ok(Math.abs(deskWire - doorWire) > 0.1, 'the wide lines miss by far');
  // … nor does a close-up's line meet a wide view's
  assert.ok(Math.abs(keys - doorWire) > 0.03 && Math.abs(lock - deskWire) > 0.03);
  // and the model agrees: zoomed out nothing links, both zoomed in it does
  const model = createPanelModel(ACTS.act05, { carry: startCarry('act05'), step: 'carrier' });
  model.state.slots = ['door', 'desk'];
  model.refreshLinks?.();
  assert.equal(model.findLink('door', 'desk', 'wire'), null);
  assert.ok(model.zoomIn('door', 'lock'));
  assert.equal(model.findLink('door', 'desk', 'wire'), null);
  assert.ok(model.zoomIn('desk', 'keys'));
  assert.ok(model.findLink('door', 'desk', 'wire'), 'both close-ups: the carrier can run');
});

test('round 7: Act 1 edges sit on the painted lines; floor and chute meet, the window and the wide wall do not', () => {
  const deskFloor = edgeAt('act1', 'desk', 'default', 'right', 'floor');
  assert.ok(Math.abs(deskFloor - ANCHOR['act1/desk'].floorRight) < 1e-9);
  for (const state of ['locked', 'unlocked', 'open']) {
    const doorFloor = edgeAt('act1', 'door', state, 'left', 'floor');
    const doorChute = edgeAt('act1', 'door', state, 'top', 'chute');
    assert.ok(Math.abs(doorFloor - deskFloor) <= 0.01, `floor meets (${state})`);
    assert.ok(Math.abs(doorChute - ANCHOR['act1/door-locked'].chute) < 1e-9);
    // the pigeonhole up close drops its chute right above the door's
    assert.ok(Math.abs(edgeAt('act1', 'lockers', 'cubby', 'bottom', 'chute') - doorChute) <= 0.01, `chute meets (${state})`);
    // the wall of pigeonholes, wide, drops its own chute further left: no link
    assert.ok(Math.abs(edgeAt('act1', 'lockers', 'wall', 'bottom', 'chute') - doorChute) > 0.03);
  }
  assert.ok(Math.abs(ANCHOR['act1/cubby'].chute - ANCHOR['act1/door-locked'].chute) <= 0.01);
  // the window bay's floor is the painted one at both edges, and lower than the corridor
  const win = edgesOf('act1', 'window', 'default');
  assert.equal(win.left[0].at, ANCHOR['act1/window'].floor);
  assert.equal(win.right[0].at, ANCHOR['act1/window'].floor);
  assert.ok(win.left[0].at - deskFloor > 0.03, 'the window floor never meets the corridor');
  // the model: wide lockers above the door do not link; zoomed in, they do
  const model = createPanelModel(ACTS.act1, { carry: startCarry('act1') });
  model.swap(0, 2);
  settle(model);
  assert.ok(model.hasFlag('butchAtDoor'));
  assert.equal(model.findLink('lockers', 'door', 'chute'), null, 'the wide wall\'s chute misses');
});

